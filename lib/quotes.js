/**
 * 적은 꿈 문장에서 주제를 찾아 어울리는 명언 한 문장을 고릅니다.
 * 같은 문장에는 항상 같은 명언이 나오도록 문자열 해시로 고릅니다.
 * @param {string} text
 * @returns {{ text: string, source: string, category: string }}
 */
export function pickQuote(text) {
  const t = (text || "").toLowerCase();
  let best = null;
  let bestHit = 0;

  for (const key of Object.keys(BANK)) {
    if (key === "base") continue;
    const hit = BANK[key].k.reduce((n, word) => (t.includes(word) ? n + 1 : n), 0);
    if (hit > bestHit) {
      bestHit = hit;
      best = key;
    }
  }

  const category = best || "base";
  const pool = BANK[category].q;

  let seed = 0;
  for (let i = 0; i < t.length; i++) seed = (seed * 31 + t.charCodeAt(i)) >>> 0;

  const [quote, source] = pool[seed % pool.length];
  return { text: quote, source, category };
}
